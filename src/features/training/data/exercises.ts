/**
 * Der mitgelieferte Uebungskatalog.
 *
 * Regeln:
 * - `id` ist stabil (snake_case) und wird NIE umbenannt: gespeicherte Saetze
 *   verweisen darauf. Neue Uebungen bekommen neue IDs; eine veraltete bleibt.
 * - `name.de` so, wie deutsche Gym-Nutzer die Uebung nennen (oft englisch:
 *   „Lat Pulldown“, „Face Pull“), `name.en` in der Schreibweise von Hevy.
 * - Fuer Suche und CSV-Import zaehlen `name.en`, `name.de` UND `aliases`.
 *   `aliases` enthaelt die abweichenden Schreibweisen aus Hevy- und
 *   Strong-Exporten (z. B. Strong „Rowing (Machine)“, Hevy „Rowing Machine“)
 *   und gaengige Kurzformen. Kein Schluessel darf zu zwei Uebungen passen
 *   (geprueft in `exercises.test.ts`, case-insensitiv).
 * - Hyrox-Stationen stehen zusaetzlich als eigene Uebungen (`hyrox_*`) mit
 *   Wettkampfdistanz im Namen; die allgemeinen Varianten (Sled Push, Wall Ball,
 *   Rudergeraet …) bleiben fuer normales Training.
 * - Gewicht bei Kurzhantel-/Farmers-Uebungen: je Hand (wie Hevy/Strong).
 */
import type {
  CatalogExercise,
  Equipment,
  ExerciseCategory,
  MuscleGroup,
  TrackingMode,
} from '../types'

function ex(
  id: string,
  de: string,
  en: string,
  category: ExerciseCategory,
  equipment: Equipment,
  tracking: TrackingMode,
  primary: MuscleGroup[],
  secondary: MuscleGroup[],
  aliases: string[] = [],
): CatalogExercise {
  const entry: CatalogExercise = { id, name: { de, en }, category, equipment, tracking, primary, secondary }
  if (aliases.length > 0) entry.aliases = aliases
  return entry
}

/** Krafttraining mit Gewicht × Wdh. */
const w = (
  id: string, de: string, en: string, equipment: Equipment,
  primary: MuscleGroup[], secondary: MuscleGroup[], aliases: string[] = [],
) => ex(id, de, en, 'strength', equipment, 'weight_reps', primary, secondary, aliases)

/** Krafttraining mit Koerpergewicht (optional Zusatzgewicht). */
const bw = (
  id: string, de: string, en: string,
  primary: MuscleGroup[], secondary: MuscleGroup[], aliases: string[] = [],
) => ex(id, de, en, 'strength', 'bodyweight', 'bodyweight_reps', primary, secondary, aliases)

/** Ausdauer mit Strecke und Zeit. */
const cardio = (
  id: string, de: string, en: string, equipment: Equipment,
  secondary: MuscleGroup[], aliases: string[] = [], tracking: TrackingMode = 'distance_duration',
) => ex(id, de, en, 'cardio', equipment, tracking, ['cardio'], secondary, aliases)

/** Mobility auf Zeit. */
const mob = (
  id: string, de: string, en: string,
  primary: MuscleGroup[], secondary: MuscleGroup[] = [], aliases: string[] = [],
  equipment: Equipment = 'bodyweight', tracking: TrackingMode = 'duration',
) => ex(id, de, en, 'mobility', equipment, tracking, primary, secondary, aliases)

/** Sprung-/Plyo-Uebung, nur Wdh. */
const plyo = (
  id: string, de: string, en: string,
  primary: MuscleGroup[], secondary: MuscleGroup[], aliases: string[] = [],
) => ex(id, de, en, 'plyometric', 'bodyweight', 'reps', primary, secondary, aliases)

